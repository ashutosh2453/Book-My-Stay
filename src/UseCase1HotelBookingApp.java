/**
 * Book My Stay Application
 *
 * This class represents the entry point of the Hotel Booking Management System.
 * It demonstrates how a Java application starts execution using the main() method
 * and prints a welcome message to the console.
 *
 * The program simply displays the application name and version information
 * when executed.
 *
 * @author Ashutosh Chauhan
 * @version 1.0
 */

public class UseCase1HotelBookingApp {

    /**
     * Main method - Entry point of the Java application.
     * The JVM starts program execution from this method.
     *
     * @param args Command line arguments
     */
    public static void main(String[] args) {

        // Display welcome message
        System.out.println("=================================");
        System.out.println("   Welcome to Book My Stay App   ");
        System.out.println("=================================");

        // Display application details
        System.out.println("Application: Hotel Booking Management System");
        System.out.println("Version: 1.0");
        System.out.println("Status: Application Started Successfully");

        // End message
        System.out.println("---------------------------------");
        System.out.println("Thank you for using Book My Stay!");
    }
}